#!/usr/bin/env python3
"""Regenerates the apps-script/*.html files so the SAME Apps Script Web App
can also serve the whole frontend, from script.google.com, instead of only
being the JSON API for a separately-hosted (GitHub Pages) site.

Why this exists: some school network filters block/degrade github.io while
already trusting google.com / googleusercontent.com (Workspace depends on
those domains), so serving the whole app from the same Apps Script URL as
the backend can route around that kind of block entirely.

Run this after editing index.html, css/styles.css, or any js/*.js file:

    python3 apps-script/build.py --deploy

--deploy additionally pushes the regenerated files to the Apps Script
project and rolls out a new version of the LIVE deployment (same URL,
same DEPLOYMENT_ID below) via `clasp`, so an update goes out with one
command and no manual copy/paste. Omit --deploy to just regenerate the
files locally without touching the live site. `clasp login` (one-time)
must already be done. Code.gs is hand-maintained, not generated -- this
script never touches it, but --deploy still pushes it along with
everything else, so edit it directly when it needs to change.

After deploying, it runs verify-live.js, which fetches the live page and checks
that every script still parses and every review in content.js is registered
(Apps Script post-processes the page and can mangle code, e.g. a `//` inside a
backtick string). You can also run it alone: node apps-script/verify-live.js
"""
import re
import subprocess
import sys
import time
from pathlib import Path

DEPLOYMENT_ID = 'AKfycbwAFlUrS72L4b6bR5rNr-RVdFXzLiZ7dqhJ8QevUVuyr5fktTRBymZ8vQI2EfxsJ2fxbQ'

ROOT = Path(__file__).resolve().parent.parent
OUT = Path(__file__).resolve().parent

# The ONE list of scripts. To add an activity, add it here (and its <script
# src> to index.html, in the same order -- main() checks they match). The
# Apps Script page's includes and apps-script/.claspignore (which files clasp
# uploads) are both generated from this list, so nothing else needs editing.
JS_FILES = [
    ('ConfigJs.html', 'js/config.js'),
    ('ContentJs.html', 'js/content.js'),
    ('StorageJs.html', 'js/storage.js'),
    ('MatterReviewJs.html', 'js/activities/matter-review.js'),
    ('ElementsReviewJs.html', 'js/activities/elements-review.js'),
    ('AtomicModelsJs.html', 'js/activities/atomic-models.js'),
    ('ParticlesReviewJs.html', 'js/activities/particles-review.js'),
    ('MovingElectronsReviewJs.html', 'js/activities/moving-electrons-review.js'),
    ('ConductivityLabJs.html', 'js/activities/conductivity-lab.js'),
    ('ElectronGlueJs.html', 'js/activities/electron-glue.js'),
    ('Unit1ReviewJs.html', 'js/activities/unit1-review.js'),
    ('CrossMultiplyDensityJs.html', 'js/activities/cross-multiply-density.js'),
    ('MiniMathReviewJs.html', 'js/activities/mini-math-review.js'),
    ('ThermometerLabJs.html', 'js/activities/thermometer-lab.js'),
    ('PhysicalChangesReviewJs.html', 'js/activities/physical-changes-review.js'),
    ('DryIceLabJs.html', 'js/activities/dry-ice-lab.js'),
    ('BoylesLawPracticeJs.html', 'js/activities/boyles-law-practice.js'),
    ('AppJs.html', 'js/app.js'),
]

INDEX_TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<base target="_top">
<title>Ionic Storm</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Space+Grotesk:wght@500;600;700&display=swap" rel="stylesheet">
<?!= include('Styles'); ?>
</head>
<body>
  <header class="site-header">
    <div class="header-inner">
      <h1 id="site-title">Ionic Storm</h1>
      <p id="site-subtitle" class="muted"></p>
    </div>
  </header>

  <main id="app"></main>

  <footer class="site-footer">
    <p>Ionic Storm &middot; Chemistry Class Hub</p>
  </footer>

{{INCLUDES}}
</body>
</html>
"""


# Files clasp must upload besides the generated scripts. Everything else in
# apps-script/ (build.py, verify-live.js, ...) stays out of the Apps Script project.
CLASP_ALWAYS = ['appsscript.json', 'Code.gs', 'Index.html', 'Styles.html']


def index_html():
    includes = '\n'.join(f"  <?!= include('{Path(name).stem}'); ?>" for name, _ in JS_FILES)
    return INDEX_TEMPLATE.replace('{{INCLUDES}}', includes)


def claspignore():
    keep = CLASP_ALWAYS + [name for name, _ in JS_FILES]
    return '# Generated by build.py from JS_FILES -- do not edit by hand.\n**/**\n' + ''.join(f'!{n}\n' for n in keep)


def check_index_matches():
    """index.html (the plain static site) must load the same scripts, in the same order."""
    srcs = re.findall(r'<script src="([^"]+)"', (ROOT / 'index.html').read_text())
    expected = [src for _, src in JS_FILES]
    if srcs != expected:
        missing = [x for x in expected if x not in srcs]
        extra = [x for x in srcs if x not in expected]
        raise SystemExit("index.html <script src> list doesn't match JS_FILES in build.py"
                         + (f"\n  missing from index.html: {missing}" if missing else '')
                         + (f"\n  in index.html but not JS_FILES: {extra}" if extra else '')
                         + ("\n  (same files, different order)" if not missing and not extra else ''))


def write(name, content):
    (OUT / name).write_text(content)
    print(f"wrote apps-script/{name} ({len(content)} bytes)")


def deploy():
    print("\nPushing to Apps Script...")
    subprocess.run(['clasp', 'push', '--force'], cwd=OUT, check=True)
    print("\nDeploying new version to the live URL...")
    subprocess.run(
        ['clasp', 'deploy', '--deploymentId', DEPLOYMENT_ID, '--description', 'build.py --deploy'],
        cwd=OUT, check=True
    )
    print("\nLive at the usual /exec URL.")
    verify_live()


def verify_live():
    """Fetch the live page and check every script parses and every review is
    registered (see verify-live.js). Retries briefly while the new version
    propagates; exits non-zero if the live site is broken."""
    print("\nVerifying the live site...")
    for attempt in range(3):
        time.sleep(5)
        result = subprocess.run(['node', str(OUT / 'verify-live.js')])
        if result.returncode == 0:
            return
        if attempt < 2:
            print("Retrying in case the new version is still propagating...")
    raise SystemExit("Live check failed -- the deployed site is broken. Fix and redeploy.")


def main():
    check_index_matches()
    styles = (ROOT / 'css/styles.css').read_text()
    write('Styles.html', f"<style>\n{styles}\n</style>")

    for out_name, src in JS_FILES:
        content = (ROOT / src).read_text()
        if '</script' in content.lower():
            raise SystemExit(f"{src} contains a literal '</script' -- would break when inlined, fix before bundling")
        write(out_name, f"<script>\n{content}\n</script>")

    write('Index.html', index_html())
    write('.claspignore', claspignore())

    if '--deploy' in sys.argv:
        deploy()


if __name__ == '__main__':
    main()
